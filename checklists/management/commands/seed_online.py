LEVELS = [
    (1, "Высокая эффективность", 51, 59),
    (2, "Достаточная эффективность", 44, 50),
    (3, "Удовлетворительная эффективность", 37, 43),
    (4, "Низкая эффективность", 0, 36),
]


class Command(BaseCommand):
    help = "Создаёт или обновляет шаблон онлайн-чек-листа"

    def handle(self, *args, **options):
        template, _ = ChecklistTemplate.objects.update_or_create(
            code="online",
            defaults={
                "name": "Чек-лист оценивания онлайн-занятия",
                "max_score": 59,
                "is_active": True,
            },
        )

        criterion_count = 0
        option_count = 0

        for section_order, section_data in enumerate(
            SECTIONS,
            start=1,
        ):
            section, _ = ChecklistSection.objects.update_or_create(
                template=template,
                order=section_order,
                defaults={
                    "title": section_data["title"],
                },
            )

            for criterion_order, criterion_data in enumerate(
                section_data["criteria"],
                start=1,
            ):
                criterion, _ = ChecklistCriterion.objects.update_or_create(
                    section=section,
                    order=criterion_order,
                    defaults={
                        "title": criterion_data["title"],
                        "comment_hint": criterion_data.get(
                            "comment_hint",
                            "",
                        ),
                    },
                )

                criterion_count += 1

                for side, key in (
                    (T, "teacher"),
                    (S, "student"),
                ):
                    options = criterion_data.get(
                        key,
                        [],
                    )

                    for option_order, (
                        score,
                        text,
                    ) in enumerate(
                        options,
                        start=1,
                    ):
                        ChecklistOption.objects.update_or_create(
                            criterion=criterion,
                            side=side,
                            order=option_order,
                            defaults={
                                "score": score,
                                "text": text,
                            },
                        )

                        option_count += 1

        for order, name, min_score, max_score in LEVELS:
            ChecklistLevel.objects.update_or_create(
                template=template,
                order=order,
                defaults={
                    "name": name,
                    "min_score": min_score,
                    "max_score": max_score,
                },
            )

        calculated_max = sum(
            criterion.max_score
            for criterion in ChecklistCriterion.objects.filter(
                section__template=template,
            )
        )

        if calculated_max != 59:
            self.stderr.write(
                self.style.ERROR(
                    f"Ошибка контроля: рассчитано "
                    f"{calculated_max}, ожидалось 59."
                )
            )
            return

        block_scores = []

        for section in template.sections.all():
            score = sum(
                criterion.max_score
                for criterion in section.criteria.all()
            )

            block_scores.append(score)

        self.stdout.write("")
        self.stdout.write(
            self.style.SUCCESS(
                "Онлайн-чек-лист создан/обновлён."
            )
        )

        self.stdout.write(
            f"Блоков: {template.sections.count()}"
        )

        self.stdout.write(
            f"Критериев: {criterion_count}"
        )

        self.stdout.write(
            f"Максимальный балл: {calculated_max}"
        )

        self.stdout.write(
            "Максимумы блоков: "
            + " + ".join(
                str(value)
                for value in block_scores
            )
        )
