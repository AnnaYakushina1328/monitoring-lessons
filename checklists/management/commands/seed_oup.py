LEVELS = [
    (1, "Высокая эффективность", 51, 57),
    (2, "Достаточная эффективность", 44, 50),
    (3, "Удовлетворительная эффективность", 37, 43),
    (4, "Низкая эффективность", 0, 36),
]


class Command(BaseCommand):
    help = "Создаёт или обновляет шаблон чек-листа ОУП"

    def handle(self, *args, **options):
        template, _ = ChecklistTemplate.objects.update_or_create(
            code="oup",
            defaults={
                "name": (
                    "Чек-лист оценивания учебного занятия "
                    "(общеобразовательные предметы, "
                    "социально-гуманитарный цикл, офлайн)"
                ),
                "max_score": 57,
                "is_active": True,
            },
        )

        criterion_count = 0
        option_count = 0

        for section_order, section_data in enumerate(SECTIONS, start=1):
            section, _ = ChecklistSection.objects.update_or_create(
                template=template,
                order=section_order,
                defaults={
                    "title": section_data["title"],
                },
            )

            for criterion_order, criterion_data in enumerate(
                section_data["criteria"],
                start=1,
            ):
                criterion, _ = ChecklistCriterion.objects.update_or_create(
                    section=section,
                    order=criterion_order,
                    defaults={
                        "title": criterion_data["title"],
                        "comment_hint": criterion_data.get(
                            "comment_hint",
                            "",
                        ),
                    },
                )

                criterion_count += 1

                for side, key in (
                    (T, "teacher"),
                    (S, "student"),
                ):
                    for option_order, option in enumerate(
                        criterion_data.get(key, []),
                        start=1,
                    ):
                        score, text = option

                        ChecklistOption.objects.update_or_create(
                            criterion=criterion,
                            side=side,
                            order=option_order,
                            defaults={
                                "score": score,
                                "text": text,
                            },
                        )

                        option_count += 1

        for order, name, min_score, max_score in LEVELS:
            ChecklistLevel.objects.update_or_create(
                template=template,
                order=order,
                defaults={
                    "name": name,
                    "min_score": min_score,
                    "max_score": max_score,
                },
            )

        calculated_max = 0

        for section in template.sections.all():
            for criterion in section.criteria.all():
                calculated_max += criterion.max_score

        if calculated_max != template.max_score:
            self.stderr.write(
                self.style.ERROR(
                    f"Ошибка контроля: рассчитано {calculated_max}, "
                    f"ожидалось {template.max_score}."
                )
            )
            return

        self.stdout.write("")
        self.stdout.write(
            self.style.SUCCESS(
                "Чек-лист ОУП успешно создан/обновлён."
            )
        )
        self.stdout.write(
            f"Блоков: {template.sections.count()}"
        )
        self.stdout.write(
            f"Критериев: {criterion_count}"
        )
        self.stdout.write(
            f"Вариантов оценки: {option_count}"
        )
        self.stdout.write(
            f"Максимальный балл: {calculated_max}"
        )
